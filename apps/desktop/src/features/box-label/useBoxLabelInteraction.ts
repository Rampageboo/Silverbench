import type { UseBoxLabelInteractionOptions } from "./boxLabelInteractionTypes";
import { useBoxLabelCanvas } from "./useBoxLabelCanvas";
import { useBoxLabelKeyboard } from "./useBoxLabelKeyboard";
import { useBoxLabelPersistence } from "./useBoxLabelPersistence";
import { useBoxLabelPointer } from "./useBoxLabelPointer";

export type { UseBoxLabelInteractionOptions } from "./boxLabelInteractionTypes";

export function useBoxLabelInteraction({
  workspaceRoot,
  datasetRoot,
  entry,
  entries,
  currentIndex,
  filename,
  onNavigate,
  onToggleReviewed,
  onToggleFlagged,
  onMarkJunk,
  onUndoJunk,
  onLabelsChanged: _onLabelsChanged,
  persistEntryLabels,
  boxesRef,
  selectedRef,
  classRef,
  dragRef,
  modeRef,
  showGridRef,
  boxAdjustModeRef,
  classesRef,
  pointerToolEnabled,
  autoFitEnabled,
  blackBoxEnabled,
  fixedBoxSlots,
  setCurrentClass,
  setBoxAdjustMode,
  recordFixedBoxFromBox,
  selectClassShortcut,
  togglePointerTool,
  toggleAutoFitTool,
  toggleBlackBoxTool,
  pushUndo,
  pushImageUndo,
  undoLast,
  redoLast,
  syncBoxToSelected,
  copySelectedBoxToNext,
  trackCsrtForward,
  setBoxes,
  setSelectedBoxId,
  setStatus,
  setError,
  setImageVersion,
  proposalsRef,
  selectedProposalIdRef,
  setSelectedProposalId,
  onMaterializeProposal
}: UseBoxLabelInteractionOptions) {
  const canvas = useBoxLabelCanvas({
    boxesRef,
    selectedRef,
    classesRef,
    showGridRef,
    dragRef,
    pointerToolEnabled,
    autoFitEnabled,
    blackBoxEnabled,
    proposalsRef,
    selectedProposalIdRef
  });

  const persistence = useBoxLabelPersistence({
    workspaceRoot,
    datasetRoot,
    entry,
    entries,
    currentIndex,
    filename,
    onNavigate,
    persistEntryLabels,
    boxesRef,
    selectedRef,
    dragRef,
    boxAdjustModeRef,
    fixedBoxSlots,
    setCurrentClass,
    pushUndo,
    pushImageUndo,
    syncBoxToSelected,
    setBoxes,
    setSelectedBoxId,
    setStatus,
    setError,
    setImageVersion,
    imageRef: canvas.imageRef,
    zoomPointRef: canvas.zoomPointRef,
    lastZoomCenterRef: canvas.lastZoomCenterRef,
    scheduleDraw: canvas.scheduleDraw
  });

  const pointer = useBoxLabelPointer({
    boxesRef,
    selectedRef,
    classRef,
    dragRef,
    modeRef,
    pointerToolEnabled,
    autoFitEnabled,
    blackBoxEnabled,
    pushUndo,
    recordFixedBoxFromBox,
    syncBoxToSelected,
    setBoxes,
    setSelectedBoxId,
    setCurrentClass,
    setError,
    canvasRef: canvas.canvasRef,
    imageRef: canvas.imageRef,
    displayRef: canvas.displayRef,
    viewportRef: canvas.viewportRef,
    zoomPointRef: canvas.zoomPointRef,
    lastZoomCenterRef: canvas.lastZoomCenterRef,
    scheduleDraw: canvas.scheduleDraw,
    applyBlackBox: persistence.applyBlackBox,
    persistLabels: persistence.persistLabels,
    proposalsRef,
    selectedProposalIdRef,
    setSelectedProposalId,
    onMaterializeProposal
  });

  useBoxLabelKeyboard({
    dragRef,
    keyboardAdjustingRef: persistence.keyboardAdjustingRef,
    setSelectedBoxId,
    setBoxAdjustMode,
    setStatus,
    setError,
    selectClassShortcut,
    togglePointerTool,
    toggleAutoFitTool,
    toggleBlackBoxTool,
    onToggleReviewed,
    onToggleFlagged,
    onMarkJunk,
    onUndoJunk,
    undoLast,
    redoLast,
    copySelectedBoxToNext,
    trackCsrtForward,
    scheduleDraw: canvas.scheduleDraw,
    save: persistence.save,
    deleteSelectedBox: persistence.deleteSelectedBox,
    createFixedBoxFromShortcut: persistence.createFixedBoxFromShortcut,
    navigateRelative: persistence.navigateRelative,
    moveSelectedBoxByKeyboard: persistence.moveSelectedBoxByKeyboard,
    resizeSelectedBoxByKeyboard: persistence.resizeSelectedBoxByKeyboard
  });

  return {
    canvasRef: canvas.canvasRef,
    stageRef: canvas.stageRef,
    zoomCanvasRef: canvas.zoomCanvasRef,
    imageRef: canvas.imageRef,
    viewportRef: canvas.viewportRef,
    zoomPointRef: canvas.zoomPointRef,
    scheduleDraw: canvas.scheduleDraw,
    save: persistence.save,
    persistLabels: persistence.persistLabels,
    onPointerDown: pointer.onPointerDown,
    onPointerMove: pointer.onPointerMove,
    onPointerUp: pointer.onPointerUp,
    onWheel: pointer.onWheel,
    restoreBackup: persistence.restoreBackup,
    deleteSelectedBox: persistence.deleteSelectedBox,
    navigateRelative: persistence.navigateRelative
  };
}
