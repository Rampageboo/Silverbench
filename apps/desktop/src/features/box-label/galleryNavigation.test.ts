import { describe, expect, it } from "vitest";
import { galleryRevealTargetForKey } from "./galleryNavigation";

describe("box label gallery reveal policy", () => {
  it("requests reveal only for valid A/D navigation", () => {
    expect(galleryRevealTargetForKey({ key: "a" }, 5, 10)).toBe(4);
    expect(galleryRevealTargetForKey({ key: "D" }, 5, 10)).toBe(6);
    expect(galleryRevealTargetForKey({ key: "ArrowRight" }, 5, 10)).toBeNull();
  });

  it("does not request reveal at dataset boundaries", () => {
    expect(galleryRevealTargetForKey({ key: "a" }, 0, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "d" }, 9, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "d" }, 0, 0)).toBeNull();
  });

  it("ignores modified shortcuts and text-editing targets", () => {
    expect(galleryRevealTargetForKey({ key: "d", ctrlKey: true }, 2, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "a", altKey: true }, 2, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "d", metaKey: true }, 2, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "d", targetTagName: "INPUT" }, 2, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "a", targetEditable: true }, 2, 10)).toBeNull();
  });

  it("ignores textarea and select targets", () => {
    expect(galleryRevealTargetForKey({ key: "d", targetTagName: "TEXTAREA" }, 2, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "a", targetTagName: "SELECT" }, 2, 10)).toBeNull();
  });

  it("handles uppercase key names via case-insensitive comparison", () => {
    expect(galleryRevealTargetForKey({ key: "A" }, 3, 10)).toBe(2);
    expect(galleryRevealTargetForKey({ key: "D" }, 3, 10)).toBe(4);
  });

  it("returns null for unrelated keys even when at a valid index", () => {
    expect(galleryRevealTargetForKey({ key: "w" }, 3, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "r" }, 3, 10)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "" }, 3, 10)).toBeNull();
  });

  it("does not request reveal for a single-item list", () => {
    // Only one item — A and D both go out of bounds.
    expect(galleryRevealTargetForKey({ key: "a" }, 0, 1)).toBeNull();
    expect(galleryRevealTargetForKey({ key: "d" }, 0, 1)).toBeNull();
  });

  // The gallery component sets pendingKeyboardRevealIndexRef.current = null on
  // every mouse click, cancelling any stale pending reveal. galleryRevealTargetForKey
  // itself is stateless — the cancellation policy is tested here at the logic
  // level by verifying no stale index is generated by a non-A/D event.
  it("stale-reveal cancellation: non-nav key produces null so any previous pending value can safely be cleared", () => {
    // The caller (BoxLabelGallery) sets pendingRef = result.
    // If result is null, the scroll-reveal effect will not fire.
    const result = galleryRevealTargetForKey({ key: "Escape" }, 5, 10);
    expect(result).toBeNull();
  });
});
