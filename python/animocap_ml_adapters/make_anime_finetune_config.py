"""Generate a conservative MMPose HRNet fine-tuning config for 12 GB VRAM."""

from __future__ import annotations

import argparse
from pathlib import Path


def make_config(
    dataset: Path,
    output: Path,
    pretrained: Path,
    epochs: int,
    batch_size: int,
) -> Path:
    import mmpose

    package_root = Path(mmpose.__file__).resolve().parent
    base = package_root / ".mim" / "configs" / "body_2d_keypoint" / \
        "topdown_heatmap" / "coco" / "td-hm_hrnet-w32_8xb64-210e_coco-256x192.py"
    if not base.is_file():
        raise RuntimeError(f"MMPose HRNet config is unavailable: {base}")
    if not (dataset / "annotations" / "train.json").is_file():
        raise RuntimeError("dataset annotations/train.json is missing")
    if not pretrained.is_file():
        raise RuntimeError(f"pretrained checkpoint is missing: {pretrained}")
    dataset_text = dataset.resolve().as_posix() + "/"
    content = f'''_base_ = [r"{base.as_posix()}"]

# Generated by AniMocap Fusion. Dataset and checkpoints remain private/local.
data_root = r"{dataset_text}"
load_from = r"{pretrained.resolve().as_posix()}"
train_cfg = dict(max_epochs={epochs}, val_interval={max(1, epochs // 8)})

train_dataloader = dict(
    batch_size={batch_size},
    num_workers=2,
    persistent_workers=True,
    dataset=dict(
        data_root=data_root,
        ann_file="annotations/train.json",
        data_prefix=dict(img="images/"),
    ),
)
val_dataloader = dict(
    batch_size={batch_size},
    num_workers=2,
    persistent_workers=True,
    dataset=dict(
        data_root=data_root,
        ann_file="annotations/val.json",
        data_prefix=dict(img="images/"),
        test_mode=True,
    ),
)
test_dataloader = val_dataloader
val_evaluator = dict(ann_file=data_root + "annotations/val.json")
test_evaluator = val_evaluator

optim_wrapper = dict(
    type="AmpOptimWrapper",
    loss_scale="dynamic",
    optimizer=dict(type="AdamW", lr=5e-5, weight_decay=0.01),
    clip_grad=dict(max_norm=1.0, norm_type=2),
)
param_scheduler = [
    dict(type="LinearLR", start_factor=0.05, by_epoch=False, begin=0, end=250),
    dict(
        type="CosineAnnealingLR", eta_min=1e-6, begin=0, end={epochs},
        T_max={epochs}, by_epoch=True, convert_to_iter_based=True,
    ),
]
auto_scale_lr = dict(base_batch_size={batch_size})
randomness = dict(seed=20260808, deterministic=False)
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    return output


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--pretrained", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=40)
    parser.add_argument("--batch-size", type=int, default=4)
    args = parser.parse_args()
    result = make_config(
        args.dataset, args.output, args.pretrained,
        max(1, args.epochs), max(1, args.batch_size),
    )
    print(result.resolve())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
